<?php

/*
 * Тренажёр: локальная генерация вопросов по материалам курсов.
 *
 * Жёсткая граница этого модуля: он НИКОГДА не пишет в exam_attempts и не
 * подменяет экзаменационные вопросы. Итоговая аттестация остаётся на
 * импортированном банке GIFT с серверной проверкой. Тренажёр существует
 * для самоподготовки и не влияет на оценки — иначе модель, ошибающаяся
 * в фактах, получала бы влияние на результат.
 *
 * Настройки перечислены здесь, а не разбросаны по коду, потому что
 * их приходится подбирать под конкретную машину: на одном сервере 3B
 * модель даёт вопрос за секунды, на другом — десятки секунд.
 */

return [

    /*
     * Общий выключатель. Даже при true всё остальное проверяется:
     * недоступный Ollama должен давать понятную ошибку в интерфейсе,
     * а не «пустой список вопросов».
     */
    'enabled' => (bool) env('TUTOR_ENABLED', false),

    /*
     *ollama или llama.cpp (сервер с OpenAI-совместимым API).
     * Требования у обоих одинаковы: generate + JSON-режим.
     */
    'provider' => env('TUTOR_PROVIDER', 'ollama'),

    'url' => rtrim((string) env('TUTOR_OLLAMA_URL', 'http://127.0.0.1:11434'), '/'),

    /*
     * Модель по умолчанию.
     *
     * По уточнённому плану — qwen3:4b (~2.5 ГБ, thinking-off) для
     * обычных CPU-машин; qwen3:8b для мощных. qwen2.5:3b — вариант для
     * совсем слабых ПК.
     *
     * Замеры на этом материале (фрагмент про гидросистемы, 5 вопросов за
     * вызов, back-check выключен) — почему нельзя взять меньше:
     *
     *   qwen2.5:0.5b-instruct (397 МБ)  3.8 с, 0 пригодных: JSON не
     *                                    выдерживает, цитаты выдумывает.
     *   qwen2.5:1.5b-instruct (986 МБ)  3.5 с, 0 пригодных: задаёт
     *                                    смыслово неверные вопросы с
     *                                    настоящей цитатой («Где
     *                                    находится гидросистема №1?» —
     *                                    ответ «правой двери», тогда как
     *                                    по фрагменту наоборот).
     *   qwen2.5:3b-instruct (1.9 ГБ)    3.5–5 с, вопросы пригодны.
     *
     * Ниже 3B порог не проходит: либо пусто, либо правдоподобная
     * бессмыслица. «Ответ подтверждается цитатой» (в
     * TutorQuestionGrounding) ловит второй случай бесплатно, но при
     * 0.5b остаётся слишком мало проходящих вопросов.
     *
     * ВАЖНО про thinking: у qwen3.* размышление включено по умолчанию и
     * съедает весь бюджет токенов — замер на qwen3.5:9b дал 96 секунд и
     * пустой content вместо 3 секунд и нормального ответа. Поэтому
     * think=false передаётся явно, и выключать TUTOR_DISABLE_THINKING
     * нельзя.
     */
    'model' => env('TUTOR_MODEL', 'qwen3:4b'),

    'disable_thinking' => (bool) env('TUTOR_DISABLE_THINKING', true),

    /*
     * Модель эмбеддингов для отбора релевантных фрагментов.
     *
     * Не обязательна: без неё (и без pgvector) релевантность считается
     * полнотекстовым поиском Postgres. Эмбеддинги дают смысловой
     * отбор, FTS — лексический, то есть «система отказа» и «отказ
     * системы» не совпадут. Это осознанный компромисс в пользу
     * отсутствия зависимости от неустановленного пакета.
     */
    'embed_model' => env('TUTOR_EMBED_MODEL', 'multilingual-e5-small'),

    /*
     * Температура. Низкая намеренно: нужна вариативность вопросов, но
     * не выдумки. Выше 0.8 модель начинает «достраивать» факты.
     *
     * Значение 0.4, а не 0.5 из плана: на слабых моделях разница между
     * 0.4 и 0.5 — это разница между воспроизводимым и «случайным»
     * вопросом, а диагностировать плохой вопрос дороже, чем сэмплировать.
     */
    'temperature' => (float) env('TUTOR_TEMPERATURE', 0.4),

    /*
     * Таймаут HTTP-запроса к движку, секунды. Генерация пачки идёт в
     * очереди, поэтому таймаут здесь — это «движок завис», а не
     * «пользователь ждёт».
     */
    'timeout' => (int) env('TUTOR_TIMEOUT', 180),

    /*
     * Сателлит (Вариант A из плана).
     *
     * Python-сервис с ChromaDB и sentence-transformers: индекс и поиск
     * по векторам живут там, потому что на машине пользователя нет
     * расширения pgvector. Пустой адрес = Вариант B, чистый PHP с
     * полнотекстовым поиском Postgres (tsvector). Оба варианта работают,
     * различается только качество отбора фрагментов.
     *
     * Векторное хранилище изолировано ПО КУРСУ (коллекция на курс), а
     * не по пользователю: права проверяет Laravel, а сателлит отвечает
     * только за поиск по тексту.
     */
    'satellite' => [
        'url' => rtrim((string) env('TUTOR_SATELLITE_URL', ''), '/'),
        'timeout' => (int) env('TUTOR_SATELLITE_TIMEOUT', 60),
    ],

    /*
     * Размер фрагмента в СИМВОЛАХ (по плану: 1800–2500 для учебников).
     *
     * Раньше считалось в токенах через грубую оценку «4 символа на
     * токен»; для русского текста такая оценка гуляет, и фактический
     * фрагмент оказывался то 1000, то 3000 символов. Символы
     * предсказуемы, а размер промпта модели всё равно считает Ollama.
     */
    'max_chunk_chars' => (int) env('TUTOR_MAX_CHUNK_CHARS', 2000),

    /* Перекрытие соседних фрагментов, чтобы не разрывать предложения. */
    'chunk_overlap_chars' => (int) env('TUTOR_CHUNK_OVERLAP_CHARS', 300),

    /* Сколько фрагментов максимум просмотреть за одну задачу. */
    'max_chunks_per_job' => (int) env('TUTOR_MAX_CHUNKS_PER_JOB', 4),

    /*
     * Back-check: сгенерированный вопрос отправляется модели обратно с
     * заданием найти подтверждение в фрагменте. Дорого (второй запрос),
     * поэтому включается настройкой.
     *
     * Не подстраховка от галлюцинаций, а именно проверка: без неё
     * единственная защита — слово «только фрагмент» в промпте, а слово
     * не является гарантией.
     *
     * По умолчанию ВЫКЛЮЧЕНО, и это следствие малых моделей. Замер на
     * qwen2.5:3b: включённый back-check стоит целого дополнительного
     * вызова на КАЖДЫЙ вопрос — то есть примерно вдвое дороже — и на
     * слабой модели даёт шум вместо пользы (пересказ подтверждения не
     * находится дословно, и результат становится случайным).
     *
     * Основную защиту теперь несут детерминированные проверки, которые
     * не могут соврать: цитата обязана дословно найтись во фрагменте,
     * а эталон — содержаться в этой цитате. Стоимость нулевая.
     *
     * Включать стоит на сильной модели (7B+) или там, где важнее
     * единичная цена вопроса, чем время ожидания.
     */
    'backcheck' => (bool) env('TUTOR_BACKCHECK', false),

    /*
     * Сколько вопросов просить за один вызов модели.
     *
     * Замер: 3 вопроса за вызов — 5.6 с на принятый вопрос, 5 вопросов
     * — 2.2 с. Промпт и фрагмент отправляются один раз, а не пять, и
     * на CPU это главный рычаг. Просить по одному — заметно дороже.
     */
    'batch_size' => (int) env('TUTOR_BATCH_SIZE', 8),

    /*
     * Через сколько секунд ожидания показывать подсказку про очередь.
     *
     * Генерация вопросов идёт в фоне (очередь database), поэтому без
     * запущенного `php artisan queue:work` задание не берётся никем:
     * интерфейс молча крутил спиннер минутами, и понять, что запуск
     * не в порядке, было невозможно. Порогового времени достаточно,
     * чтобы отличить «модель думает» от «задание ещё не начали».
     */
    'worker_stall_seconds' => (int) env('TUTOR_WORKER_STALL_SECONDS', 45),

    /*
     * Бюджет токенов на ответ.
     *
     * 1200 был с запасом и на практике означал, что модель может
     * думать полминуты там, где хватит сотни токенов. Пять вопросов
     * с цитатами и вариантами укладываются примерно в 600.
     */
    'max_tokens' => (int) env('TUTOR_MAX_TOKENS', 700),

    /*
     * Сколько токенов примерно стоит один вопрос с вариантами и цитатой.
     * Нужно, чтобы ограничить число вопросов в вызове по бюджету:
     * просить больше, чем бюджет вмещает, означает обрыв JSON и ноль
     * пригодных вопросов за потраченное время.
     */
    'tokens_per_question' => (int) env('TUTOR_TOKENS_PER_QUESTION', 110),

    /* Бюджет на back-check: там нужен только короткий вердикт. */
    'backcheck_tokens' => (int) env('TUTOR_BACKCHECK_TOKENS', 300),

    /* Очередь для фоновой генерации. */
    'queue' => env('TUTOR_QUEUE', 'default'),

    /*
     * Права. Объявлены здесь, чтобы синхронизация с каталогом прав
     * (PermissionCatalog) и этим файлом не расходилась: право, которого
     * нет в каталоге, не выдаётся ни одной ролью, и страница молча
     * отдаёт 403.
     */
    'permissions' => [
        'use' => 'tutor.use',
        'manage' => 'tutor.manage',
    ],

    /*
     * Типы вопросов. mcq — с вариантами и одним правильным, short —
     * краткий ответ со сверкой с эталоном, open — открытый ответ с
     * оценкой моделью против эталона.
     */
    'question_types' => ['mcq', 'short', 'open'],

    /*
     * Типы по умолчанию: без открытых ответов, потому что оценка
     * свободного текста моделью — самое слабое место, и на первом
     * запуске оно сразу портит впечатление.
     */
    'default_types' => ['mcq', 'short'],
];