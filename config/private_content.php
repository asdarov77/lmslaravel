<?php

/*
 * Раздача приватного контента курсов.
 *
 * Зачем файл: отдача материала — единственное место в приложении, где
 * байты файла целиком проходят через PHP. На курсе с сотней тем
 * браузер тянет index.html, стили, скрипты и картинки, то есть сотни
 * запросов; каждый из них занимает worker PHP-FPM на всё время потока.
 * Под нагрузкой первым падает именно этот путь.
 *
 * Два режима, переключается галкой в админке (Настройки → Раздача
 * материалов), значение хранится в settings.content_delivery:
 *
 *   php    — текущее поведение: контроллер читает файл и отдаёт его
 *            потоком через response()->stream(). Работает везде, где
 *            есть PHP, ничего не требует от веб-сервера. Значение по
 *            умолчанию: режим nginx без настроенного location ломает
 *            выдачу целиком.
 *
 *   nginx  — контроллер проверяет подпись и отвечает пустым телом с
 *            заголовком X-Accel-Redirect. Дальше файл открывает сам
 *            nginx: sendfile без копирования в userspace, поддержка
 *            Range/If-Modified-Since, gzip/brotli, и ни одного занятого
 *            worker'а PHP. Тело ответа при этом пустое — отдаёт nginx.
 *
 * Почему не «просто отдать файл nginx без Laravel»: подпись в пути
 * (HMAC от aircraft|auk|expires на APP_KEY) проверяется приложением,
 * и это единственная точка, где решается «можно ли этому пользователю
 * вот этот курс». nginx про подписи ничего не знает. Поэтому проверка
 * подписи остаётся в middleware, а nginx включается только ПОСЛЕ неё.
 */

return [

    /*
     * Режим по умолчанию, когда в settings нет строки content_delivery
     * (или значение в ней недопустимо). Пустая строка = не задано.
     */
    'delivery' => env('PRIVATE_CONTENT_DELIVERY', 'php'),

    /*
     * Имя настройки в таблице settings. Значение: 'php' | 'nginx'.
     */
    'setting_name' => 'content_delivery',

    /*
     * Внутренний location nginx, который отдаёт файлы.
     *
     * Должен быть помечен `internal`: снаружи такой location недоступен
     * и отдаёт 404. Открыть его вручную нельзя — X-Accel-Redirect
     * работает только на location с internal, это и делает раздачу
     * невозможной в обход проверки подписи.
     *
     * Менять нужно одновременно в config и в конфиге nginx.
     */
    'accel_internal' => env('PRIVATE_CONTENT_ACCEL_INTERNAL', '/_protected-content'),

    /*
     * Cache-Control для материала.
     *
     * Именно private, а не public: подписанная ссылка одна на всех
     * записанных, и общий кэш (CDN, Varnish, Squid) отдал бы файл
     * тому, кто её не получал. TTL короче TTL подписи (30 минут),
     * иначе кэш переживёт отзыв доступа.
     */
    'cache_control' => env('PRIVATE_CONTENT_CACHE_CONTROL', 'private, max-age=600, must-revalidate'),

    /*
     * Максимальный размер файла, который режим nginx готов отдать.
     *
     * Файлы крупнее отдаёт PHP: X-Accel-Redirect не ограничивает
     * отдачу, а очень большой файл через internal-location упирается в
     * sendfile и таймауты. Необязательный параметр — 0 снимает
     * ограничение.
     */
    'accel_max_bytes' => (int) env('PRIVATE_CONTENT_ACCEL_MAX_BYTES', 0),

    /*
     * Метка «запрос пришёл через nginx».
     *
     * Не задаётся по умолчанию намеренно: значение вычисляется из
     * APP_KEY, чтобы не было второй настройки, о которой забудут.
     * Переопределение нужно только если конфиг nginx собирается не
     * этой командой, а вручную и на другой машине.
     *
     * Проверяется так: приложение отдаёт X-Accel-Redirect только если
     * видит этот заголовок с правильным значением. Без nginx (например
     * `php artisan serve`) заголовка нет, и раздача молча уходила бы в
     * пустое тело со статусом 200.
     */
    'accel_marker' => env('PRIVATE_CONTENT_ACCEL_MARKER'),

];
