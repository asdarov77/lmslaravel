<?php

/*
 * Файловый менеджер: где лежат файлы и как их загружают.
 *
 * Отдельный файл, потому что у файлового менеджера ТРИ настройки, которые
 * нельзя положить в config/filesystems.php:
 *
 *   1. корневой каталог пользовательских файлов;
 *   2. размер чанка при загрузке больших файлов;
 *   3. предел размера одного файла.
 *
 * Первые две связаны с тем, как nginx и PHP-FPM принимают тело запроса
 * (см. deploy/nginx-content-delivery.conf и docs/nginx-x-accel-setup.md).
 */

return [

    /*
     * Диск, на котором лежат пользовательские файлы.
     *
     * Именно `local` (storage/app), а НЕ `public` (storage/app/public).
     * Разница принципиальна: каталог `public` попадает под корень
     * веб-сервера через `php artisan storage:link`, и всё, что туда
     * легло, становится доступно по адресу /storage/... без проверки
     * прав. Старый FilesController::upload писал в uploads/{ФИО} на
     * диске по умолчанию, и одна смена FILESYSTEM_DISK=public тихо
     * делала личные файлы доступными всем, у кого есть ссылка.
     * Каталог пользовательских файлов намеренно вне public/.
     */
    'disk' => env('FILE_MANAGER_DISK', 'local'),

    /*
     * Корневой каталог внутри диска. Файлы пользователя N лежат в
     * {disk root}/{root}/{N}/...
     *
     * Идентификатором служит id пользователя, а не ФИО: ФИО меняется,
     * а каталог останется, и файлы пользователя окажутся в папке,
     * имя которой больше никто не найдёт.
     */
    'root' => trim((string) env('FILE_MANAGER_ROOT', 'userfiles'), '/'),

    /*
     * Размер чанка при загрузке больших файлов, байт.
     *
     * Зачем чанки, если есть upload_max_filesize: лимит PHP стоит на
     * каждом запросе, а не на файле целиком. Файл режется на куски и
     * отправляется отдельными запросами, поэтому 10 ГБ проходят через
     * те же 8 МБ, что и файл на 8 МБ. Второе следствие — докачка:
     * оборванная загрузка продолжается с последнего принятого куска,
     * а не начинается заново.
     *
     * ВАЖНО: значение должно быть заметно МЕНЬШЕ двух пределов, и оба
     * задаются НЕ в приложении:
     *   - post_max_size / upload_max_filesize в php.ini (FPM-пул);
     *   - client_max_body_size в nginx (по умолчанию 1m — запрос
     *     большего размера отбивается с 413 ещё до PHP).
     * Рассчитать значение для своей машины: `php artisan
     * files:limits`. Пока ограничения не подняты, уменьшите CHUNK.
     */
    'chunk_bytes' => (int) env('FILE_MANAGER_CHUNK_BYTES', 4 * 1024 * 1024),

    /*
     * Максимальный размер одного файла, байт. 0 — без ограничения.
     *
     * Ограничение нужно, потому что объявленный клиентом размер — это
     * обещание, а не факт: без предела один запрос может заполнить
     * диск. Проверяется и объявленный размер, и фактически принятый
     * объём частей.
     */
    'max_bytes' => (int) env('FILE_MANAGER_MAX_BYTES', 4 * 1024 * 1024 * 1024),

    /*
     * Сколько живёт незавершённая загрузка, секунд.
     *
     * Части лежат во временном каталоге и занимают место. Загрузка,
     * брошенная на середине, должна исчезнуть сама — иначе одна
     * неудачная попытка оставляет на диске половину файла навсегда.
     * Чистка: `php artisan files:prune-uploads`.
     */
    'upload_ttl' => (int) env('FILE_MANAGER_UPLOAD_TTL', 24 * 60 * 60),

    /*
     * Сколько файлов можно отметить и переместить/удалить одним
     * действием. Защита от запроса на тысячу идентификаторов.
     */
    'max_bulk' => (int) env('FILE_MANAGER_MAX_BULK', 500),
];
