<?php

namespace App\Support\Tutor;

use RuntimeException;

/**
 * Нейродвижок недоступен: выключен, не отвечает, ответил мусором.
 *
 * Отдельный тип нужен, чтобы отличать «движка нет» от «движок есть, но
 * вопросы плохие». Первое — состояние окружения, показывается в
 * интерфейсе и чинится настройкой; второе — рабочая ситуация, из-за
 * которой просто пропускается пачка вопросов.
 *
 * Без этого разделения обработчик в контроллере превращал бы и то и
 * другое в 500, и пользователь видел бы «что-то сломалось» вместо
 * «поставьте Ollama».
 */
class TutorUnavailableException extends RuntimeException
{
    public static function disabled(): self
    {
        return new self('Тренажёр выключен (TUTOR_ENABLED=false)');
    }
}