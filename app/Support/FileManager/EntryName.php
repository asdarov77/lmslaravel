<?php

namespace App\Support\FileManager;

use Illuminate\Validation\ValidationException;

/**
 * Проверка одного имени файла или папки.
 *
 * Имена приходят из браузера, и доверять им нельзя: `../../../etc`,
 * `a/b`, имя с NUL внутри и пустое имя — не «грязные данные», а способ
 * записать файл за пределы каталога пользователя или вообще за пределы
 * диска. Поэтому проверка одна и применяется ко всем входам: загрузка,
 * переименование, создание папки. Обойти её нельзя, потому что
 * контроллеры не собирают путь сами — они зовут EntryName::clean и
 * получают уже безопасное имя.
 *
 * Проверка НАМЕРЕННО возвращает 422 с понятным текстом, а не 403 или
 * 500: «имя файла недопустимо» — это ошибка ввода пользователя, и
 * показать её надо в том же диалоге, где имя вводят.
 */
final class EntryName
{
    /**
     * Каталог временных частей лежит ВНУТРИ корня пользователя, поэтому
     * его имя зарезервировано: папка `.uploads` перекрыла бы временные
     * файлы и дала бы возможность писать в служебный каталог.
     */
    public const RESERVED = ['.', '..', '.uploads'];

    /** Максимальная длина имени в символах (не байтах). */
    public const MAX_LENGTH = 200;

    /**
     * Приводит имя к безопасному виду или объясняет, почему не вышло.
     *
     * Порядок важен: сначала отбраковка по символам (здесь и
     * отсекаются разделители пути), затем обрезка краёв. Обрезать
     * пробелы ДО проверки опасно: «.. » станет «..» и пройдёт как
     * обычное имя, хотя это попытка выйти из каталога.
     *
     * @throws ValidationException
     */
    public static function clean(string $raw, string $label = 'Имя'): string
    {
        // NUL обрезает строку во многих системных вызовах, поэтому
        // проверяем ДО обрезки краёв и санитайзеров.
        if (str_contains($raw, "\0")) {
            throw self::fail($label);
        }

        // Пробелы по краям убираем молча: этим же занимается TrimStrings
        // в глобальном стеке middleware, и отказ на «имени с пробелом
        // справа» удивил бы пользователя сильнее, чем молчаливая обрезка.
        $name = trim($raw);

        if ($name === '') {
            throw self::fail($label);
        }

        // Управляющие символы и разделители. Символ DEL (0x7F) в имени
        // тоже не нужен, а вот точка внутри имени («отчёт.2024.pdf»)
        // разрешена — запрещаются только ведущая и хвостовая.
        if (preg_match('#[\\\\/\x00-\x1F\x7F]#u', $name) === 1) {
            throw self::fail($label);
        }

        /*
         * Точка в начале или в конце ЗАПРЕЩЕНА, а не срезается.
         *
         * Это принципиально: молчаливая обрезка превращает запрос
         * «создай папку .имя» в папку «имя», и пользователь не понимает,
         * куда попал файл. Отказ с текстом — единственный вариант, при
         * котором результат совпадает с ожиданием.
         *
         * Заодно закрывается путь «..»: без запрета ведущей точки имя
         * «..» после среза стало бы пустым, а «.uploads» — служебным
         * каталогом незавершённых загрузок.
         *
         * Хвостовая точка запрещена ещё и потому, что Windows не
         * различает «имя.» и «имя»: файл, который здесь назывался
         * «отчёт.», на другой машине стал бы «отчёт» — два разных
         * файла в одной папке.
         */
        if (str_starts_with($name, '.') || str_ends_with($name, '.')) {
            throw self::fail($label);
        }

        if (in_array($name, self::RESERVED, true)) {
            throw self::fail($label);
        }

        if (mb_strlen($name) > self::MAX_LENGTH) {
            throw ValidationException::withMessages([
                'name' => sprintf('%s длиннее %d символов.', $label, self::MAX_LENGTH),
            ]);
        }

        return $name;
    }

    /**
     * Очищает имя и, если надо, подгоняет под лимит длины, сохранив
     * расширение. Имя из браузера может оказаться длиннее лимита, и
     * молча обрезать его нельзя — обрезка молча меняет имя.
     *
     * @throws ValidationException
     */
    public static function cleanShort(string $raw, string $label = 'Имя'): string
    {
        $name = self::clean($raw, $label);

        if (mb_strlen($name) <= self::MAX_LENGTH) {
            return $name;
        }

        $ext = self::extension($name);
        $stem = $ext === '' ? $name : mb_substr($name, 0, mb_strlen($name) - mb_strlen($ext) - 1);

        // Расчёт на символы, а не байты: кириллическое имя в 200
        // символов занимает в UTF-8 вдвое больше байт, и обрезка по
        // байтам порвала бы файл посреди символа.
        $keep = self::MAX_LENGTH - ($ext === '' ? 0 : mb_strlen($ext) + 1);

        return mb_substr($stem, 0, max(1, $keep)) . ($ext === '' ? '' : '.' . $ext);
    }

    /**
     * Расширение без точки, в нижнем регистре. Пустая строка, если
     * расширения нет.
     */
    public static function extension(string $name): string
    {
        $dot = mb_strrpos($name, '.');

        // Точка в начале имени не считается расширением, но после
        // clean() ведущих точек не остаётся — проверка остаётся для
        // прямых вызовов из тестов и импорта.
        if ($dot === false || $dot === 0) {
            return '';
        }

        return mb_strtolower(mb_substr($name, $dot + 1));
    }

    /**
     * Имя без расширения.
     */
    public static function stem(string $name): string
    {
        $ext = self::extension($name);

        return $ext === '' ? $name : mb_substr($name, 0, mb_strlen($name) - mb_strlen($ext) - 1);
    }

    /**
     * Заменяет расширение (или добавляет его). Используется, когда
     * при несовпадении имён к имени дописывается «(2)»: расширение
     * обязано остаться на месте, иначе получится «отчёт(2).pdf.txt».
     */
    public static function withSuffix(string $name, string $suffix): string
    {
        $ext = self::extension($name);
        $stem = $ext === '' ? $name : self::stem($name);

        return $stem.$suffix.($ext === '' ? '' : '.'.$ext);
    }

    /**
     * Имя для занятого варианта: «отчёт.pdf» → «отчёт (2).pdf».
     *
     * Уже имеющийся номер отбрасывается: без этого «отчёт (2).pdf»,
     * имя которого уже занято, превращалось бы в «отчёт (2) (2).pdf», а
     * на третьем повторе — в «отчёт (2) (2) (3).pdf». Пользователь,
     * который трижды загружал «отчёт», получил бы имя, которое уже
     * никогда не поймёт.
     *
     * Снимается только хвостовой « (число)», и только если он в самом
     * конце расширения: имя «отчёт (2) черновик.pdf» не трогается, там
     * скобки — часть названия.
     */
    public static function numbered(string $name, int $index): string
    {
        $ext = self::extension($name);
        $stem = $ext === '' ? $name : self::stem($name);

        $base = preg_replace('/ \(\d+\)$/u', '', $stem) ?? $stem;

        return $base.' ('.$index.')'.($ext === '' ? '' : '.'.$ext);
    }

    /**
     * Ошибка ввода. Ключ `name` — тот же, что у поля в диалоге, поэтому
     * страница может подсветить нужное поле, а не показывать текст
     * «где-то ошибка».
     *
     * @return never
     */
    private static function fail(string $label): ValidationException
    {
        return ValidationException::withMessages([
            'name' => sprintf(
                '%s: запрещены символы «/», «\\», точка в начале или в конце, пустое имя.',
                $label
            ),
        ]);
    }
}
