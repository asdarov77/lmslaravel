/**
 * Демонстрационные пользователи.
 *
 * Регресс: group_id был зашит константами 1, 2, 3. Groups создаются
 * фабрикой, поэтому их id не обязаны начинаться с единицы: достаточно
 * одного предыдущего заполнения sequence (RefreshDatabase откатывает
 * транзакцию, но НЕ сбрасывает sequence — в PostgreSQL nextval не
 * transactional), и сидер падал с
 * «Key (group_id)=(1) отсутствует в таблице groups».
 *
 * Теперь id групп резолвятся по фактическому содержимому таблицы, а если
 * групп меньше, чем нужно, они досоздаются.
 */
class UserSeeder extends Seeder
{
    /**
     * Демо-пользователи: [fio, роль, номер группы].
     *
     * @var array<int, array{0: string, 1: string, 2: int}>
     */
    private const USERS = [
        ['Администратор', 'Администратор', 1],
        ['Иванов Иван Иванович', 'Инструктор', 1],
        ['Петров Иван Иванович', 'Обучаемый', 1],
        ['Сидоров Иван Иванович', 'Обучаемый', 1],
        ['Корнеев Иван Иванович', 'Обучаемый', 1],
        ['Семенов Иван Иванович', 'Обучаемый', 1],
        ['Крупнов Максим Витальевич', 'Обучаемый', 1],
        ['Ненадович Иван Иванович', 'Обучаемый', 1],
        ['Пименов Иван Иванович', 'Инструктор', 1],
        ['Пельш Иван Иванович', 'Обучаемый', 1],
        ['Моисеев Иван Иванович', 'Обучаемый', 2],
        ['Рабинович Хаим Иванович', 'Обучаемый', 2],
        ['Медведев Дмитрий Анатольевич', 'Обучаемый', 2],
        ['Трунов Иван Семенович', 'Обучаемый', 2],
        ['Селезнев Тимофей Михайлович', 'Инструктор', 2],
        ['Нагиев Дмитрий Владимирович', 'Обучаемый', 3],
        ['Шойгу Сергей Кужугетович', 'Обучаемый', 3],
        ['Великов Вадим Иванович', 'Обучаемый', 3],
        ['Фурсов Андрей Ильич', 'Обучаемый', 3],
        ['Савельев Сергей Вячеславович', 'Обучаемый', 3],
        ['Панчин Александр Юрьевич', 'Обучаемый', 3],
    ];

    public function run()
    {
        $groupIds = $this->resolveGroupIds();

        // Один хэш на всех: при 21 пользователе считать его в цикле
        // бессмысленно дорого, а пароль у демо-пользователей общий.
        $password = Hash::make('123');

        $rows = [];
        foreach (self::USERS as [$fio, $role, $groupNumber]) {
            $rows[] = [
                'fio' => $fio,
                'role' => $role,
                'password' => $password,
                'group_id' => $groupIds[$groupNumber],
                // Почта нужна для восстановления пароля. Берём транслит
                // ФИО: кириллические адреса не везде поддерживаются.
                'email' => self::emailFor($fio),
            ];
        }

        /*
         * Поштучный updateOrCreate по fio, а не пакетный insert.
         *
         * users.fio уникален, поэтому повторный запуск insert() падал
         * с UniqueConstraintViolationException — а наполовину
         * засеянная база хуже пустой. fio — естественный ключ
         * человека, по нему и создаётся запись.
         */
        foreach ($rows as $row) {
            $attributes = [
                'role' => $row['role'],
                'group_id' => $row['group_id'],
                'email' => $row['email'],
                'updated_at' => now(),
            ];

            /*
             * Пароль пишется только при СОЗДАНИИ.
             *
             * Два требования противоречат друг другу: при вставке
             * пароль обязателен (NOT NULL), а при обновлении его
             * затирать нельзя — иначе повторный запуск сидеров сбрасывал
             * бы пароли живых людей, заданные ими после создания.
             */
            if (! DB::table('users')->where('fio', $row['fio'])->exists()) {
                $attributes['password'] = $row['password'];
                $attributes['created_at'] = now();
            }

            DB::table('users')->updateOrInsert(['fio' => $row['fio']], $attributes);
        }
    }

    /**
     * Почтовый адрес из ФИО.
     *
     * Транслитерация, а не кириллический адрес: почтовые сервисы и
     * старые клиенты кириллицу в from/to не принимают, а письмо со
     * ссылкой восстановления обязано дойти.
     */
    private static function emailFor(string $fio): string
    {
        static $map = [
            'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd',
            'е' => 'e', 'ё' => 'e', 'ж' => 'zh', 'з' => 'z', 'и' => 'i',
            'й' => 'y', 'к' => 'k', 'л' => 'l', 'м' => 'm', 'н' => 'n',
            'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't',
            'у' => 'u', 'ф' => 'f', 'х' => 'kh', 'ц' => 'ts', 'ч' => 'ch',
            'ш' => 'sh', 'щ' => 'shch', 'ъ' => '', 'ы' => 'y', 'ь' => '',
            'э' => 'e', 'ю' => 'yu', 'я' => 'ya',
        ];

        $ascii = strtr(mb_strtolower($fio), $map);
        $slug = preg_replace('/[^a-z0-9]+/', '.', $ascii);
        $slug = trim($slug, '.');

        return $slug . '@example.com';
    }

    /**
     * Возвращает id групп по их порядковому номеру (1, 2, 3…),
     * создавая недостающие группы.
     *
     * @return array<int, int> карта «номер группы => id»
     */
    private function resolveGroupIds(): array
    {
        $needed = max(array_column(self::USERS, '2'));
        $ids = Group::orderBy('id')->pluck('id')->all();

        if (count($ids) < $needed) {
            // Групп меньше, чем требуется сидеру: досоздаём недостающие,
            // иначе FK users_group_id_foreign нарушится.
            //
            // Досоздаём группы с читаемыми именами, а не через фабрику.
            // Фабрика даёт случайные слова («quas», «iure»), которые
            // потом невозможно отличить ни в выпадающих списках, ни в
            // отчётах. Имя — естественный ключ: повторный запуск обновит
            // существующую группу, а не создаст «Группа 1 (2)».
            foreach (range(1, $needed) as $number) {
                Group::updateOrCreate(
                    ['groupname' => 'Группа ' . $number],
                    ['groupname' => 'Группа ' . $number]
                );
            }

            $ids = Group::orderBy('id')->pluck('id')->all();
        }

        // Нумерация с единицы: $groupIds[1] — первая группа.
        return array_combine(range(1, $needed), array_slice($ids, 0, $needed));
    }
}