import { chromium } from 'playwright'
const ok=(n,c,d='')=>console.log(`${c?'OK  ':'FAIL'} ${n}${d?' — '+d:''}`)
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox','--disable-dev-shm-usage'] })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const errs=[]; p.on('pageerror',e=>errs.push(e.message))
await p.goto('http://127.0.0.1:8080/#/login', { waitUntil: 'networkidle' })
await p.fill('#userLogin','Администратор'); await p.fill('#password','123')
await p.click('button[type="submit"]'); await p.waitForTimeout(2500)
await p.evaluate(() => { window.location.hash = '#/courses/itemmani?idEdit=65' })
await p.waitForTimeout(3500)

const notes = p.locator('.cpl__notes')
ok('панель заметок видна', await notes.count() > 0)
if (await notes.count()) {
  await notes.locator('summary').click()
  const area = notes.locator('textarea')
  await area.fill('Тестовая заметка по курсу')
  await area.blur()
  await p.waitForTimeout(500)
  ok('заметка сохранилась', (await p.evaluate(() => localStorage.getItem('course-notes-65'))) === 'Тестовая заметка по курсу')
  // перезагрузка — заметка должна вернуться
  await p.reload({ waitUntil: 'networkidle' })
  await p.waitForTimeout(2500)
  await p.evaluate(() => { window.location.hash = '#/courses/itemmani?idEdit=65' })
  await p.waitForTimeout(3000)
  const val = await p.locator('.cpl__notes textarea').inputValue().catch(()=>null)
  ok('заметка пережила перезагрузку', val === 'Тестовая заметка по курсу', val)
}
console.log('ошибки:', errs.length?errs.slice(0,2):'нет')
await b.close()
