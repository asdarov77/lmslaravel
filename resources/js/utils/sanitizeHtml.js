/**
 * Санитизация HTML материала курса.
 *
 * Материал может быть набран в визуальном редакторе или загружен файлом,
 * поэтому в него можно «зашить» исполнимый код. Первый барьер —
 * sandbox-атрибут у iframe в плеере; эта функция — второй барьер:
 * документ перед вставкой в srcdoc лишается скриптов и обработчиков.
 *
 * Строчная регулярка вместо DOMPurify: только теги <script>, inline-обработчики
 * событий и ссылки javascript-схемы; парсер ради трёх операций тянуть не надо.
 *
 * shortcut: regex-санитизация не граница безопасности — барьер здесь
 * именно sandbox-атрибут iframe; regex нужен, чтобы в srcdoc не
 * попадал хлам, который sandbox не убирает (замусоренный DOM).
 */
export function sanitizeMaterialHtml(html) {
  return String(html)
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, '')
    .replace(/ on[a-z]+="[^"]*"/gi, '')
    .replace(/ on[a-z]+='[^']*'/gi, '')
    .replace(/javascript:/gi, '')
    .replace(/<iframe\b[^>]*>(?:[\s\S]*?<\/iframe>)?/gi, '')
}
